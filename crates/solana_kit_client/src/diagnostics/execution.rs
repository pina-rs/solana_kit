impl InstructionFailure {
    /// Stable pinned code for this execution variant.
    pub fn error_code(&self) -> Option<ErrorCode> {
        INSTRUCTIONS
            .iter()
            .find(|(variant, _)| discriminant(variant) == discriminant(self))
            .and_then(|(_, code)| *code)
    }
}
