pub(super) fn instructions() -> Result<Vec<Value>, Error> {
    LEGACY
        .iter()
        .chain(MODERN)
        .map(|entry| instruction(entry, entry.0 < 41))
        .collect()
}

fn instruction((tag, name, payload, accounts): &Entry, omitted: bool) -> Result<Value, Error> {
    let mut arguments = vec![
        json!({"kind":"instructionArgumentNode","name":"discriminator",
        "type":number("u8"),"defaultValue":{"kind":"numberValueNode","number":tag},
        "defaultValueStrategy":"omitted"}),
    ];
    arguments.extend(fields(payload, "instructionArgumentNode")?);

    Ok(
        json!({"kind":"instructionNode","name":name,"arguments":arguments,
        "accounts":roles(accounts)?,"optionalAccountStrategy":if omitted {"omitted"} else {"programId"},
        "discriminators":[{"kind":"fieldDiscriminatorNode","name":"discriminator","offset":0}]}),
    )
}
