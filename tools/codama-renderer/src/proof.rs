//! Executed byte and Kit-owned instruction proof for two generated encoders.

use crate::generated::{self, CreateAccount, CreateAccountWithSeed};
use solana_kit_core::{AccountMeta, AccountRole, Address, Instruction};

/// Translates the official renderer's account policy into Kit-owned values.
fn instruction(payer: Address, new_account: Address, data: Vec<u8>) -> Instruction {
    Instruction {
        program_address: Address::from_bytes([0; 32]),
        accounts: vec![
            AccountMeta {
                address: payer,
                role: AccountRole::WritableSigner,
            },
            AccountMeta {
                address: new_account,
                role: AccountRole::WritableSigner,
            },
        ],
        data,
    }
}

/// Compares generated bytes to independent literal wire fixtures.
pub(crate) fn run() -> Result<(), Box<dyn std::error::Error>> {
    let owner = Address::from_bytes([4; 32]);
    let data = generated::create_account(&CreateAccount {
        lamports: 256,
        space: 513,
        program_address: owner,
    })?;
    let invocation = instruction(
        Address::from_bytes([1; 32]),
        Address::from_bytes([2; 32]),
        data,
    );
    let seeded = generated::create_account_with_seed(&CreateAccountWithSeed {
        base: Address::from_bytes([3; 32]),
        seed: "é".into(),
        amount: 256,
        space: 513,
        program_address: owner,
    })?;
    let oracles = include_str!("../fixtures/oracles.txt");
    let expected: Vec<_> = oracles
        .lines()
        .filter(|line| !line.starts_with('#'))
        .collect();
    let hex = |bytes: &[u8]| {
        bytes
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect::<String>()
    };

    if hex(&invocation.data) != expected[0] || hex(&seeded) != expected[1] {
        return Err("generated encoder disagrees with independent byte oracle".into());
    }

    if invocation.accounts.len() != 2
        || invocation
            .accounts
            .iter()
            .any(|meta| meta.role != AccountRole::WritableSigner)
    {
        return Err("CreateAccount account policy differs from pinned source".into());
    }

    println!(
        "executed Kit-owned CreateAccount (52 bytes) and UTF-8 CreateAccountWithSeed (94 bytes)"
    );
    Ok(())
}
